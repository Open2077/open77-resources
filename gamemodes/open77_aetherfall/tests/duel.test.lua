local function training()
    local d=AetherfallDuel.new(Aetherfall,{practice=true})
    assert(d:join(1,"Sol")); assert(d:join(2,"Luna"))
    d:setReady(1,true); d:setReady(2,true)
    d:position(1,pos(0,-8),0); d:position(2,pos(0,0),0)
    assert(d:addDummy(-1,"Sentinel",pos(0,8),200))
    d:step(0); d:drain(); return d
end
test("training grounds cast at once and only dummies take damage",function()
    local d=training(); assert(d.phase=="practice" and d.members[1].alive)
    assert(d:cast(1,"lance",aim,1)); tick(d,1000)
    -- The lance passes through the mage standing between and strikes the dummy behind.
    assert(d.members[2].hp==200 and d.members[-1].hp==152 and d.members[1].hits==1)
    d:damage(2,1,50,"bolt",pos(0,0)); assert(d.members[2].hp==200)
end)
test("training dummy falls, rises again and the phase never changes",function()
    local d=training(); d.members[-1].hp=20
    assert(d:cast(1,"bolt",aim,1)); tick(d,1000)
    assert(not d.members[-1].alive and d.members[1].kills==1 and d.phase=="practice")
    local events=d:drain(); local fell=false
    for _,e in ipairs(events) do if e.kind=="eliminated" and e.dummy then fell=true end end
    assert(fell)
    tick(d,Aetherfall.training.respawnMs+100)
    assert(d.members[-1].alive and d.members[-1].hp==200)
end)
test("training snapshot lists dummies apart from the roster",function()
    local d=training(); local s=d:snapshot(1)
    assert(s.practice and #s.roster==2 and #s.dummies==1 and s.dummies[1].maxHp==200 and s.self.hits==0)
    assert(d:snapshot(-1).self==nil)
end)
test("a moving dummy is struck where the adapter puts it",function()
    local d=training(); assert(d:moveDummy(-1,pos(10,8)))
    assert(d:cast(1,"lance",aim,1)); tick(d,1000); assert(d.members[-1].hp==200)
    assert(d:cast(1,"bolt",{x=10/math.sqrt(10^2+16^2),y=16/math.sqrt(10^2+16^2),z=0},2)); tick(d,1500)
    assert(d.members[-1].hp==178)
end)
test("a match started from the lobby finishes instead of starting again",function()
    local d=AetherfallDuel.new(Aetherfall,{finish=true})
    assert(d:join(1)); assert(d:join(2)); d:setReady(1,true); d:setReady(2,true)
    d:position(1,pos(0,-8),0); d:position(2,pos(0,8),0); d:step(0)
    d:placed(1,d.epoch); d:placed(2,d.epoch); d:step(0); tick(d,5000)
    d.members[1].wins=2; d:damage(2,1,200,"bolt",pos(0,8)); d:step(d.now)
    assert(d.phase=="results"); tick(d,Aetherfall.rules.resultMs+100); assert(d.phase=="finished")
    tick(d,1000); assert(d.phase=="finished")
end)
