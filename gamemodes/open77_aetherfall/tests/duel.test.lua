    local t=AetherfallDuel.contact(pos(-10,0,1),pos(10,0,1),pos(0,0),0.1)
    assert(t and t>0.4 and t<0.5)
    assert(not AetherfallDuel.contact(pos(-10,0,5),pos(10,0,5),pos(0,0),0.1))
end)
test("misses spend cooldown without damage",function()
    local d=fixture(); assert(d:cast(1,"bolt",{x=1,y=0,z=0},1)); tick(d,2000)
    assert(d.members[2].hp==200 and #d.projectiles==0)
end)
test("replays cooldown invalid aim and mana are authoritative",function()
    local d=fixture(); assert(d:cast(1,"lance",aim,1))
    local mana=d.members[1].mana
    local ok,err=d:cast(1,"lance",aim,1); assert(not ok and err=="stale_cast")
    ok,err=d:cast(1,"lance",aim,2); assert(not ok and err=="cooldown")
    assert(d.members[1].mana==mana)
    tick(d,500)
    ok,err=d:cast(1,"nova",{x=0/0,y=0,z=1},3); assert(not ok and err=="invalid_aim")
    d.members[1].mana=0
    ok,err=d:cast(1,"nova",aim,4); assert(not ok and err=="mana")
end)
test("ward absorbs damage and expires on server clock",function()
    local d=fixture(); assert(d:cast(2,"ward",aim,1)); assert(d:cast(1,"lance",aim,1))
    tick(d,1000); assert(d.members[2].hp==200 and d.members[2].shield==17)
    assert(d:cast(1,"bolt",aim,2)); tick(d,900)
    assert(d.members[2].hp==195 and d.members[2].shield==0)
    tick(d,600); assert(d.members[2].shield==0)
end)
