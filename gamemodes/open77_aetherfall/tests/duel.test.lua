local passed=0
local function test(name,fn)
    local ok,err=pcall(fn); assert(ok,name..": "..tostring(err)); passed=passed+1; print("PASS "..name)
end
local center=Aetherfall.arena.center
local function pos(x,y,z) return {x=center.x+x,y=center.y+y,z=center.z+(z or 0)} end
local function fresh(d)
    for id,p in pairs(d.members) do if p.position then d:position(id,p.position,d.now) end end
end
local function tick(d,ms)
    local endAt=d.now+ms
    while d.now<endAt do fresh(d); d:step(math.min(endAt,d.now+50)) end
end
local function fixture()
    local d=AetherfallDuel.new(Aetherfall)
    assert(d:join(1,"Sol")); assert(d:join(2,"Luna"))
    d:setReady(1,true); d:setReady(2,true)
    d:position(1,pos(0,-8),0); d:position(2,pos(0,8),0)
    d:step(0); assert(d.phase=="preparing")
    d:placed(1,d.epoch); d:placed(2,d.epoch); d:step(0)
    tick(d,5000); assert(d.phase=="active"); d:drain(); return d
end
local aim={x=0,y=1,z=0}
test("placement acknowledgement gates countdown",function()
    local d=AetherfallDuel.new(Aetherfall)
    d:join(1); d:join(2); d:setReady(1,true); d:setReady(2,true); d:step(0)
    assert(not d:placed(1,d.epoch-1)); d:placed(1,d.epoch)
    tick(d,10000); assert(d.phase=="preparing")
    d:placed(2,d.epoch); d:step(d.now); assert(d.phase=="countdown")
end)
test("projectile flight and first contact",function()
    local d=fixture(); assert(d:cast(1,"bolt",aim,1))
    tick(d,200); assert(d.members[2].hp==200)
    tick(d,600); assert(d.members[2].hp==178 and #d.projectiles==0)
end)
