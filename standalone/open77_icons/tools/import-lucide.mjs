// Reproducible, offline import of the pinned upstream static SVG package.
// npm pack lucide-static@1.47.0 --ignore-scripts, then extract the package first.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
assert.ok(source, "Pass the extracted lucide-static package directory");
const check = process.argv.includes("--check");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = JSON.parse(await readFile(path.join(source, "package.json"), "utf8"));
assert.equal(upstream.name, "lucide-static");
assert.equal(upstream.version, "1.47.0");
const names = (await readdir(path.join(source, "icons"))).filter(n => n.endsWith(".svg")).sort();
const entries = [];
const writes = new Map();
for (const file of names) {
  assert.match(file, /^[a-z0-9][a-z0-9-]*\.svg$/);
  const raw = (await readFile(path.join(source, "icons", file), "utf8")).replaceAll("\r\n", "\n");
  assert.match(raw, /viewBox="0 0 24 24"/);
  // Remove browser-only classes; retain upstream geometry and flat paint.
  // Native blips reject out-of-viewBox strokes instead of clipping them.
  const svg = raw.replace(/\s+class="[^"]*"/g, "")
    .replace('viewBox="0 0 24 24"', 'viewBox="-2 -2 28 28"').trim() + "\n";
  const name = file.slice(0, -4);
  const asset = `icons/lucide/${file}`;
  writes.set(asset, svg);
  entries.push({ name, asset, sha256: createHash("sha256").update(svg).digest("hex") });
}
const catalogue = { library: "Lucide", version: upstream.version,
  source: "https://github.com/lucide-icons/lucide", license: "ISC; Feather-derived icons MIT",
  packageIntegrity: "sha512-yWIrkdXc688Feq5VjOktsKmV5Ikc7y5Nu3rrdtbr8nWjkJWk8QlnZfVtIak22Af+fNhZ7k4cTJpZo1zmj7X5sA==",
  modifications: "Browser classes removed; viewBox padded by 2 units on each side to contain strokes.",
  count: entries.length, icons: entries };
writes.set("catalogue.json", JSON.stringify(catalogue, null, 2) + "\n");
writes.set("client/catalogue.lua", '-- Generated by tools/import-lucide.mjs; do not edit.\nOpen77IconCatalogue = {\n'
  + entries.map(e => `    "${e.name}",`).join("\n") + '\n}\n');
writes.set("LICENSE-LUCIDE.txt", await readFile(path.join(source, "LICENSE"), "utf8"));
for (const [target, text] of writes) {
  const destination = path.join(root, target);
  if (check) assert.equal((await readFile(destination, "utf8")).replaceAll("\r\n", "\n"), text.replaceAll("\r\n", "\n"), target);
  else { await mkdir(path.dirname(destination), { recursive: true }); await writeFile(destination, text); }
}
console.log(`${check ? "Verified" : "Imported"} ${entries.length} Lucide ${upstream.version} SVG icons; no runtime network dependency.`);
