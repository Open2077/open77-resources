-- The manifest's own page, used when `WebUI.create` is called with no `entry`.
-- Both surfaces here name their entry explicitly (`web/index.html` and
-- `web/menu.html`); a `create` only succeeds for a file declared in `web_files`
-- below, which the `web/**` glob covers.
web_ui_page "web/index.html"
web_ui_auto_create false
web_files { "web/**" }

-- Least privilege, but honestly: an admin package needs most of the platform.
-- The manifest permission grants access to a BINDING; it never replaces the
-- per-call ACL check on `command.<name>`, which is what actually authorises an
-- operator. See docs and the resource README.
permissions {
    -- Read the server's compiled ACL for per-action availability and revocation.
    -- This is not an ACL writer and never replaces restricted command dispatch.
    "acl.read",
    -- Client: the pause key, so the panel closes with everything else.
    "local.events",

    -- Client: `Open77.input.isDown` / `isCaptured`, which is how the compact
    -- `/admin` menu is driven.
    --
    -- This grants a POLL of raw key state, and nothing else -- there is no
    -- binding to synthesise, consume or rebind a key anywhere in the API. The
    -- menu reads it precisely SO THAT it does not have to take focus: a focused
    -- surface would get the keys by swallowing them from the game, which is the
    -- failure this feature exists to avoid. `isCaptured` is the other half:
    -- when chat or the full panel legitimately owns the keyboard, the menu
    -- stands down instead of fighting for the arrow keys.
    "input.actions",
    -- Both halves: the panel's data channel and the travel/governor delegation.
    --
    -- It is also the ONLY grant the Weapons tab needs, which is worth stating
    -- because it looks like an omission. `Open77.weapons.*` on the SERVER is
    -- not a native: it is Lua in the host prelude that fires
    -- `open77:weapons:request` at one authenticated session and waits for
    -- `open77:weapons:result` -- so it is gated by `network.events` like every
    -- other server-to-client call and by nothing else. `player.weapons.read`
    -- and `player.weapons.edit` gate the CLIENT-side natives, which this
    -- package never touches: the work happens inside `open77_weapons`, whose
    -- own manifest declares them.
    "network.events",

    -- Server: the roster, life and health.
    "players.life.read",
    "players.model.read",
    "players.model.control",
    "players.life.kill",
    "players.life.revive",
    "players.life.respawn",
    "players.damage.read",
    "players.damage.apply",
    "players.stats.read",
    "players.stats.apply",
    "players.disconnect",
    "players.access", -- durable server-local bans; never an ACL role writer

    -- Server: spawning, removing, repairing, flags.
    "world.vehicles",

    -- Server: world props, lights and effects. Both bindings are read-open and
    -- write-scoped by the host: any resource may LIST every prop, and only the
    -- resource that created one may move, re-light or remove it. So these two
    -- grants buy the Props tab its own set dressing and nothing over anybody
    -- else's.
    "world.props",
    "world.effects",
    -- Read native door state for the local, ACL-authorised Developer inspector.
    "world.doors",

    -- Client: noclip / fly / direct teleport, delegated from an ACL-checked
    -- server command. The local lab commands are refused while a multiplayer
    -- session is active, so this is the only online path.
    "player.travel",

    -- Client: read streamed vehicles, and cap them.
    --
    -- `vehicles.performance` gates a native that landed after 2.31.0+op77.7 and
    -- is NOT in any shipped client. Declaring it is safe regardless: neither
    -- ResourceManifestParser.cs nor ResourceHost.cpp validates a permission
    -- name against a list, so an unknown name is inert rather than fatal.
    "vehicles.read",
    "vehicles.performance",

    -- Client: /admin.self.pos copies a transform the operator can paste.
    "clipboard.write"
}
