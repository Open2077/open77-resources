-- Replacing a live CEF surface while gameplay is running has historically
-- caused unstable transitions, so every resource that owns one declares
-- "reconnect". There is no rules half here to protect from that: the panel IS
-- the resource, so a split would buy an export boundary nothing crosses.
reload_policy "reconnect"

-- Listed explicitly, one per line, never globbed. `server/**/*.lua` requires an
-- intermediate directory and matches nothing against a flat `server/main.lua`;
-- an empty glob stops the resource, and on the client side it refuses the WHOLE
-- session resource set with `script_pattern_empty:` and nobody can connect.
--
-- Manifest order IS load order (fixed 2026-08-26), and the server half reaches
-- across its files through one plain global, `Admin`, declared by main.lua. So
-- main.lua must come first.
shared_script "shared/config.lua"

-- The catalogue is SEVERAL files, and the order below is load order, which it
-- depends on: the head creates the table, the columns fill it, the index parts
-- read `records` and must come last. The last one asserts that all of them
-- ran, so a mistake here fails the resource loudly instead of shipping half a
-- catalogue.
--
-- It is split because the host aborts a script load that crosses 10 000 VM
-- instructions on a stalled frame, and rolls back the whole candidate resource
-- set when it does -- which reads as "my deploy did nothing" rather than as an
-- error. shared/catalog.lua carries the full note. Do not merge them, and do
-- not hand-edit them: tools/build-catalog.py emits this list.
