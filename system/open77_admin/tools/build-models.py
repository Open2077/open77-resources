#!/usr/bin/env python3
"""Generate the morph discovery index from the checked-in 2.31 NPC extraction.

No record here is a runtime allowlist or a certification of animation support.
The Lua data is a single string: parsing is sliced on the server, never during
resource load or on every client. Run with --check to detect generated drift.
"""
import argparse
import csv
import hashlib
import io
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SOURCE = ROOT / "docs/generated/npc-records-2.31.csv"


def outputs():
    raw = SOURCE.read_bytes()
    rows = sorted((r for r in csv.DictReader(io.StringIO(raw.decode("utf-8-sig")))
                   if r["record"].startswith("Character.")), key=lambda r: r["record"].lower())
    assert rows and len({r["record"] for r in rows}) == len(rows)
    for row in rows:
        assert re.fullmatch(r"Character\.[A-Za-z0-9_.-]+", row["record"])
        assert all(re.fullmatch(r"[a-z_]+", row[k]) for k in ("category", "risk"))
    digest = hashlib.sha256(raw).hexdigest()
    data = "\n".join("\t".join(r[k] for k in ("record", "category", "risk")) for r in rows)
    lua = ("-- Generated by tools/build-models.py; discovery only, not an allowlist.\n"
           f"-- Source CSV SHA-256: {digest}\n"
           f'Open77AdminModels = {{ count = {len(rows)}, game = "2.31", records = [=[\n{data}\n]=] }}\n')
    md = ("# Player morph record list — Cyberpunk 2077 2.31\n\n"
          f"All **{len(rows):,} `Character.*` IDs** from the checked-in base-game/Phantom Liberty extraction. "
          "Internal `TEST.*` IDs are excluded. This is not an animation compatibility guarantee.\n\n"
          "Use `SetPlayerModel(playerId, record)` server-side with `players.model.control`. "
          "Use `ResetPlayerModel(playerId)` to restore the player's appearance. "
          "Custom mod records remain accepted when installed on all clients.\n\n"
          "Rogue and Johnny have humanoid vehicle coverage; Smasher's special rig has a known vehicle-pose limitation. "
          "Other entries require testing; quest, child, player-body and nonhuman records need special care.\n\n"
          f"Source: `docs/generated/npc-records-2.31.csv` · SHA-256 `{digest}`.\n\n"
          "| Record ID | Category | Extraction classification |\n| --- | --- | --- |\n")
    md += "".join(f'| `{r["record"]}` | {r["category"]} | {r["risk"]} |\n' for r in rows)
    return {ROOT / "resources/system/open77_admin/server/models-data.lua": lua,
            ROOT / "docs/generated/player-models-2.31.md": md}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.read_text(encoding="utf-8") == content, f"Generated drift: {path}"
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
        print(path.relative_to(ROOT))

