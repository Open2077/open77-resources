-- Light RP performance stages and engine sounds (DRAFT): which record is which stage and which
-- sound. The records themselves come from this resource's preload_mod (TweakXL):
--   Vehicle.<dealer record>             stage 0, factory sound
--   Vehicle.<dealer record>_o77s<n>     stage n, factory sound
--   Vehicle.<dealer record>_o77a<k>     stage 0, sound k
--   Vehicle.<dealer record>_o77s<n>a<k> stage n, sound k
-- Changing a car's stage or sound is a server decision (respawnAs(id, record),
-- docs/vehicle-visual-contract.md section 6): never accept a record name from a client, ask
-- this table for it. Changing the stage keeps the sound, changing the sound keeps the stage.
-- Generated by scripts/vehicle-kit/stages/build-stages.ps1 from stages/lua/stages_main.lua.
local TAG = '[@@RESOURCE@@]'
local Sounds = type(LightRpEngineSounds) == 'table' and LightRpEngineSounds or nil
-- The combinations the pack does not generate: their record would collide with another
-- TweakDBID (STAGES.md, TweakDBID collisions). record -> stage -> sound ids. Such a record
-- does not exist in the game: nothing here ever names it, and the server learns the hole
-- from registerEngineSounds (the sound's coverage omits that stage for that model).
local missing = Sounds and type(Sounds.missing) == 'table' and Sounds.missing or {}
local byRecord = {}   -- record -> { model = stage model, stage = 0..3, sound = sound entry | nil }
local soundById = {}
local stageCount, soundCount = 0, 0

local function recordFor(model, stage, sound)
    if not sound then
        if stage == 0 then return model.record end
        return model.stages[stage]
    end
    return model.record .. '_o77' .. (stage > 0 and ('s' .. stage) or '') .. 'a' .. sound.index
end

-- False for a combination `missing` lists.
local function generated(record, stage, sound)
    local holes = missing[record] and missing[record][stage]
    if not sound or not holes then return true end
    for _, id in ipairs(holes) do
        if id == sound.id then return false end
    end
    return true
end

-- The sounds of a model's class (car sounds on cars, bike sounds on bikes), in catalogue order;
-- with `stage`, only those the pack generated a record for at that stage.
local function soundsOf(record, stage)
    local info = Sounds and Sounds.models[record]
    if not info then return {} end
    local out = {}
    for _, sound in ipairs(Sounds.sounds) do
        if sound.class == info.class and (stage == nil or generated(record, stage, sound)) then out[#out + 1] = sound end
    end
    return out
end

if Sounds then
    for _, sound in ipairs(Sounds.sounds) do soundById[sound.id] = sound end
end
for _, model in ipairs(LightRpVehicleStages.models) do
    local sounds = soundsOf(model.record)
    for stage = 0, #model.stages do
        byRecord[recordFor(model, stage)] = { model = model, stage = stage }
        if stage > 0 then stageCount = stageCount + 1 end
        for _, sound in ipairs(sounds) do
            if generated(model.record, stage, sound) then
                byRecord[recordFor(model, stage, sound)] = { model = model, stage = stage, sound = sound }
                soundCount = soundCount + 1
            end
        end
    end
end

-- The record of `model` at `stage` with `sound` (nil = factory), or nil and why: 'wrong_class'
-- (a sound of the other class) or 'sound_not_for_stage' (a combination the pack does not
-- generate: keep the factory sound at that stage, or another stage).
local function resolve(model, stage, sound)
    local candidate = recordFor(model, stage, sound)
    if byRecord[candidate] then return candidate end
    local info = Sounds and Sounds.models[model.record]
    if sound and info and sound.class == info.class then return nil, 'sound_not_for_stage' end
    return nil, 'wrong_class'
end

-- stageRecord(record of the model at any stage and sound, stage 0..3) -> record | nil, reason.
-- The sound of `record` is kept ('sound_not_for_stage' when the pack has no such record).
exports('stageRecord', function(record, stage)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    stage = math.tointeger(stage)
    if not stage or stage < 0 or stage > #entry.model.stages then return nil, 'invalid_stage' end
    return resolve(entry.model, stage, entry.sound)
end)

-- stageOf(record) -> model key, stage (0 = no stage), sound id (nil = factory) | nil, reason
exports('stageOf', function(record)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    return entry.model.key, entry.stage, entry.sound and entry.sound.id or nil
end)

-- engineSoundRecord(record of the model at any stage and sound, sound id | nil) -> record | nil, reason.
-- nil = the factory sound. The stage of `record` is kept.
exports('engineSoundRecord', function(record, soundId)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    if soundId == nil then return recordFor(entry.model, entry.stage) end
    local sound = soundById[soundId]
    if not sound then return nil, 'unknown_sound' end
    return resolve(entry.model, entry.stage, sound)
end)

-- composeRecord(record of the model at any stage and sound, stage 0..3, sound id | nil) -> record | nil, reason.
-- For a garage restore: the dealer record plus the stored stage and sound give the record to spawn.
exports('composeRecord', function(record, stage, soundId)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    stage = math.tointeger(stage)
    if not stage or stage < 0 or stage > #entry.model.stages then return nil, 'invalid_stage' end
    local sound = nil
    if soundId ~= nil then
        sound = soundById[soundId]
        if not sound then return nil, 'unknown_sound' end
    end
    return resolve(entry.model, stage, sound)
end)

-- engineSoundOf(record) -> sound id, or nil for the factory sound | nil, 'unknown_record'
exports('engineSoundOf', function(record)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    return entry.sound and entry.sound.id or nil
end)

-- engineSounds(record?) -> { { id, label, class, factory } ... }: every sound, or those the
-- record's model takes at the record's stage. `factory` marks the set the model already has.
exports('engineSounds', function(record)
    local list, info = Sounds and Sounds.sounds or {}, nil
    if record ~= nil then
        local entry = byRecord[record]
        if not entry then return {} end
        list = soundsOf(entry.model.record, entry.stage)
        info = Sounds and Sounds.models[entry.model.record] or nil
    end
    local out = {}
    for _, sound in ipairs(list) do
        out[#out + 1] = { id = sound.id, label = sound.label, class = sound.class,
                          factory = info ~= nil and info.factorySet == sound.set }
    end
    return out
end)

-- ratedTopSpeedKmh(record) -> km/h | nil, reason. Stages never raise it (gears untouched):
-- a speed well above this is a plausibility flag, not a stage.
exports('ratedTopSpeedKmh', function(record)
    local entry = byRecord[record]
    if not entry then return nil, 'unknown_record' end
    return entry.model.ratedTopSpeedKmh
end)

-- The wave-2 server learns the sounds from this call (PLAN-vehicle-custom-wave2.md, W2.3):
-- { { id, label, class, set, index, models = { staged base records of the class }, maxStage } ... }.
-- A sound with a combination in `missing` sends the map form instead, models = { [record] =
-- { stages generated } }, so the server's coverage (VehicleEngineSound.Covers) is false exactly
-- there and it never composes that record.
local function coverage(records, sound)
    local holed = false
    for _, record in ipairs(records) do
        for stage = 0, Sounds.maxStage do
            if not generated(record, stage, sound) then holed = true end
        end
    end
    local models = {}
    for i, record in ipairs(records) do
        if not holed then
            models[i] = record
        else
            local stages = {}
            for stage = 0, Sounds.maxStage do
                if generated(record, stage, sound) then stages[#stages + 1] = stage end
            end
            if #stages > 0 then models[record] = stages end
        end
    end
    return models
end

local function registerSounds()
    if not Sounds then return end
    if type(Open77.vehicles.registerEngineSounds) ~= 'function' then
        print(TAG .. ' Open77.vehicles.registerEngineSounds is missing on this server: the engine '
            .. 'sounds are only reachable through /enginesound (respawnAs) until the wave-2 natives land')
        return
    end
    local byClass = {}
    for record, info in pairs(Sounds.models) do
        byClass[info.class] = byClass[info.class] or {}
        table.insert(byClass[info.class], record)
    end
    for _, records in pairs(byClass) do table.sort(records) end
    local catalogue = {}
    for _, sound in ipairs(Sounds.sounds) do
        catalogue[#catalogue + 1] = { id = sound.id, label = sound.label, class = sound.class, set = sound.set,
                                      index = sound.index, models = coverage(byClass[sound.class] or {}, sound),
                                      maxStage = Sounds.maxStage }
    end
    local ok, why = Open77.vehicles.registerEngineSounds(catalogue)
    print(('%s registerEngineSounds: %s %s'):format(TAG, tostring(ok), tostring(why or '')))
end

local function reply(player, raw, ok, text)
    print(TAG .. ' ' .. text)
    if player and player > 0 then TriggerClientEvent('open77:command:result', player, raw or '', ok == true, text) end
    return ok
end

local function vehicleFor(player, explicit)
    if explicit then
        local id = tonumber(explicit)
        if id and Open77.vehicles.get(id) then return id end
        return nil, 'no vehicle ' .. tostring(explicit)
    end
    local seat = Open77.vehicles.getPlayerSeat(player)
    if seat and seat.vehicleId and Open77.vehicles.get(seat.vehicleId) then return seat.vehicleId end
    return nil, 'sit in a car or pass its id'
end

local function respawn(player, raw, vehicle, target, what)
    local id, reason = Open77.vehicles.respawnAs(vehicle, target)
    if not id then return reply(player, raw, false, ('respawnAs %s: %s'):format(target, tostring(reason))) end
    return reply(player, raw, true, ('%s -> %s'):format(what, target))
end

-- Lab command (restricted, server ACL command.enginesound): /enginesound list|off|<sound id> [vehicleId]
-- Uses Open77.vehicles.setEngineSound when the server has it (the persisted, replicated path),
-- otherwise respawns the car on the record directly.
RegisterCommand('enginesound', function(player, args, raw)
    local verb = args[1] or 'list'
    local vehicle, why = vehicleFor(player, args[2])
    if not vehicle then return reply(player, raw, false, why) end
    local record = Open77.vehicles.get(vehicle).record
    local entry = byRecord[record]
    if not entry then return reply(player, raw, false, record .. ' is not a staged model (dealer or extended)') end
    if verb == 'list' then
        local names = {}
        for _, sound in ipairs(soundsOf(entry.model.record, entry.stage)) do
            names[#names + 1] = ('%s "%s"'):format(sound.id, sound.label)
        end
        return reply(player, raw, true, ('%s: stage %d, sound %s; choices: %s'):format(record, entry.stage,
            entry.sound and entry.sound.id or 'factory', table.concat(names, ', ')))
    end
    local soundId = verb ~= 'off' and verb or nil
    if type(Open77.vehicles.setEngineSound) == 'function' then
        local ok, reason = Open77.vehicles.setEngineSound(vehicle, soundId)
        return reply(player, raw, ok, ok and ('engine sound ' .. tostring(soundId or 'factory'))
            or ('setEngineSound: ' .. tostring(reason)))
    end
    local target, reason = (function()
        local sound = soundId and soundById[soundId]
        if soundId and not sound then return nil, 'unknown_sound' end
        return resolve(entry.model, entry.stage, sound)
    end)()
    if not target then return reply(player, raw, false, ('sound %s: %s'):format(tostring(verb), reason)) end
    return respawn(player, raw, vehicle, target, 'engine sound ' .. tostring(soundId or 'factory'))
end, true)

-- Lab command (restricted, server ACL command.perfstage): /perfstage <0-3> [vehicleId]. Keeps the sound.
RegisterCommand('perfstage', function(player, args, raw)
    local number = tonumber(args[1] or '')
    local stage = number and math.tointeger(number)
    local vehicle, why = vehicleFor(player, args[2])
    if not vehicle then return reply(player, raw, false, why) end
    local record = Open77.vehicles.get(vehicle).record
    local entry = byRecord[record]
    if not entry then return reply(player, raw, false, record .. ' is not a staged model (dealer or extended)') end
    if not stage or stage < 0 or stage > #entry.model.stages then
        return reply(player, raw, false, 'usage: /perfstage <0-' .. #entry.model.stages .. '> [vehicleId]')
    end
    local target, reason = resolve(entry.model, stage, entry.sound)
    if not target then
        return reply(player, raw, false, ('stage %d with sound %s: %s'):format(stage, entry.sound.id, reason))
    end
    return respawn(player, raw, vehicle, target, 'stage ' .. stage)
end, true)

AddEventHandler('onResourceStart', function(resource)
    if resource ~= GetCurrentResourceName() then return end
    print(('%s %d models, %d stage records, %d engine sound records (stages yaml %s, sounds yaml %s)'):format(
        TAG, #LightRpVehicleStages.models, stageCount, soundCount, LightRpVehicleStages.yamlSha256:sub(1, 12),
        Sounds and Sounds.yamlSha256:sub(1, 12) or 'none'))
    registerSounds()
end)
