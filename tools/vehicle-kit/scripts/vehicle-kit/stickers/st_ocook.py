"""Native cook of the ORIGINAL sticker pack: placements.json + imported meshes in, WolvenKit JSON + TweakXL YAML out.

    python st_ocook.py prepare  <cook.json>   decal meshes, decal entities, YAML, Lua catalogue, catalogue JSON, package.json
    python st_ocook.py validate <cook.json>   serialize round trip of every file + the textures (lv_cook.validate)
    python st_ocook.py scan-names <scan-plan.json>   the binary blocks plates.cjs scan found shared
                                              are CR2W names tables or vertex format descriptors
                                              (scan_names), else it fails

Everything the pack carries is OURS, made the way the livery pack makes its decals
(liveries/lv_cook.py, reused read-only):
    <prefix>\\textures\\<theme>_<motif>_{d,m}.xbm    the motif (st_art.py): BC7 sRGB colour with the
                                                    cut-out in its alpha, BC4 mask
    <prefix>\\meshes\\<model>\\<theme>_<zone>.mesh   the decal geometry (st_place.py), imported on the
                                                    container mesh, its material a local instance of
                                                    stickers.mi (lv_cook.decal_material)
    <prefix>\\decals\\<model>\\<theme>_<zone>.ent    one entMeshComponent "decal" (lv_cook.decal_entity)
The only references outside the pack are stickers.mi and the flat normal (allowedReferences).

TweakXL records (Vehicle.* namespace, nothing vanilla is modified), the sticker pack's shapes:
    Vehicle.o77_os_<model>_<theme>_<zone>          VehicleDecalAttachment: host component + our .ent
    Vehicle.o77_sticker_os_<model>_<theme>         VehicleColorTemplate used as a list holder: its
                                                   customDecals = the set's decal records; in no
                                                   AppearancesToColorTemplate
Catalogue: one sticker per (theme, model), id os.<model>.<theme>, `decals` = its decal count
(the integer getDecalBudget and the Light RP studio sum), in the registerStickers shape.
"""
from __future__ import annotations

import json
import re
import struct
import sys
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'liveries'))
import lv_cook  # noqa: E402  (read-only reuse)
from lv_common import BS, MAX_DECALS_PER_TEMPLATE, flat_name, read_json, write_json  # noqa: E402
from lv_cook import check_depot, decal_entity, depot_paths, prepare_mesh  # noqa: E402

RECORD_RE = re.compile(r'^Vehicle\.o77_[a-z0-9_]{1,116}$')
ID_RE = re.compile(r'^[a-z0-9][a-z0-9_.-]{0,63}$')
COMPONENT_RE = re.compile(r'^[A-Za-z0-9_]{1,128}$')
LUA_SAFE = re.compile(r'^[\x20-\x7e]*$')
MAX_MODELS = 64              # server VehicleStickerCatalogue.MaximumModels: the records one sticker may list


def fail(msg):
    raise SystemExit(f'st_ocook: {msg}')


def yq(s):
    return "'" + str(s).replace("'", "''") + "'"


def lua_str(s):
    s = str(s)
    if not LUA_SAFE.match(s):
        fail(f'non-ASCII text for Lua: {s!r}')
    return json.dumps(s)


def record(name):
    if not RECORD_RE.match(name):
        fail(f'record name refused: {name}')
    return name


def prepare(cfg):
    spec, placements = read_json(cfg['spec']), read_json(cfg['placements'])
    place_dir = Path(cfg['placements']).parent
    prefix, out = cfg['prefix'], Path(cfg['preparedDir'])
    cap = int(spec['maxDecalsPerCar'])
    if cap > MAX_DECALS_PER_TEMPLATE:
        fail(f'maxDecalsPerCar {cap} is above the engine cap {MAX_DECALS_PER_TEMPLATE}')
    themes = {t['id']: t for t in spec['themes']}
    textures = {}
    for t in cfg['textures']:
        textures.setdefault(t['motif'], {})[t['kind']] = check_depot(t['depot'], prefix, '.xbm')
    imported = {(m['model'], m['theme'], m['zone']): m for m in cfg['meshes']}
    files, decal_records, sticker_records, meshes_rep = [], [], [], OrderedDict()
    yaml = [
        '# Open77 Light RP ORIGINAL vehicle stickers: decal attachments and per-set decal lists (TweakXL).',
        f"# Generated by scripts/vehicle-kit/stickers/build-original-stickers.ps1, revision {cfg['revision'][:12]}. "
        'Edit the spec, not this file.',
        '# Each decal = OUR .ent -> OUR .mesh -> OUR .xbm (original motif art), hung on a stock component of the',
        '# player appearance. Each Vehicle.o77_sticker_os_* record only lists decals: it is in no',
        '# AppearancesToColorTemplate, so the game never applies it as a paint job.',
        '',
    ]
    catalogue, models_out = [], OrderedDict()
    for s in placements['sets']:
        key, theme = s['model'], themes[s['theme']]
        n = len(s['decals'])
        if n != s['decalCount'] or not 1 <= n <= cap:
            fail(f'{key}/{theme["id"]}: {n} decals (cap {cap}; 13 crash every client at spawn)')
        parts = []
        for d in s['decals']:
            if not COMPONENT_RE.match(d['host']):
                fail(f'{key}/{d["zone"]}: component name refused: {d["host"]}')
            stem = d['stem']
            t = imported.get((key, theme['id'], d['zone'])) or fail(f'no imported mesh for {key}/{theme["id"]}/{d["zone"]}')
            mesh_depot = check_depot(f'{prefix}{BS}meshes{BS}{key}{BS}{theme["id"]}_{d["zone"]}.mesh', prefix, '.mesh')
            doc, colours = prepare_mesh(cfg, key, d['zone'], {'importedJson': t['importedJson'], 'glb': str(place_dir / d['glb'])},
                                        [stem], {stem: textures[stem]}, mesh_depot)
            write_json(out / (flat_name(mesh_depot) + '.json'), doc)
            ent = check_depot(f'{prefix}{BS}decals{BS}{key}{BS}{theme["id"]}_{d["zone"]}.ent', prefix, '.ent')
            write_json(out / (flat_name(ent) + '.json'), decal_entity(mesh_depot, stem, ent, cfg['wolvenkit']))
            files += [mesh_depot, ent]
            rec = record(f'{spec["decalPrefix"]}{key}_{theme["id"]}_{d["zone"]}')
            decal_records.append(rec)
            meshes_rep[mesh_depot] = {'triangles': d['triangles'], 'vertexColorsChecked': colours, 'motif': stem}
            parts.append(OrderedDict([('record', rec), ('component', d['host']), ('decal', ent)]))
            yaml += [
                f'{rec}:',
                '  $type: VehicleDecalAttachment',
                f'  componentToAttachTo: {yq(d["host"])}',
                f'  decalResource: {yq(ent)}',
                '  onlyForPlayerVehicleAppearances: []',
                '',
            ]
        holder = record(f'{spec["stickerPrefix"]}{spec["idPrefix"]}_{key}_{theme["id"]}')
        yaml += [
            f'{holder}:',
            '  $type: VehicleColorTemplate',
            '  hasCustomPattern: true',
            '  mainColor: []',
            '  secondaryColor: []',
            '  lightsHue: -1.0',
            '  matchingAppearances: []',
            '  matchingColorVariant: []',
            '  partsClearCoatOverrides: []',
            '  customMultilayers: []',
            '  customDecals:',
            *[f'    - {p["record"]}' for p in parts],
            '',
        ]
        sticker_records.append(holder)
        sid = f'{spec["idPrefix"]}.{key}.{theme["id"]}'
        if not ID_RE.match(sid):
            fail(f'sticker id refused: {sid}')
        records = list(s.get('records') or [s['record']])
        if records[0] != s['record'] or len(set(records)) != len(records) or len(records) > MAX_MODELS:
            fail(f'{key}/{theme["id"]}: records must start with the primary {s["record"]}, once each, '
                 f'{MAX_MODELS} at most (server MaximumModels)')
        catalogue.append(OrderedDict([
            ('id', sid), ('label', theme['label']), ('group', theme['group']), ('model', s['record']),
            *([('models', records)] if len(records) > 1 else []),
            ('decals', n), ('record', holder), ('parts', parts),
        ]))
        for r in records:
            models_out.setdefault(r, OrderedDict([('key', key), ('stickers', [])]))['stickers'].append(sid)
    if len(set(decal_records + sticker_records)) != len(decal_records) + len(sticker_records):
        fail('duplicate record names')
    if len({c['id'] for c in catalogue}) != len(catalogue):
        fail('duplicate sticker ids')
    Path(cfg['yamlOut']).parent.mkdir(parents=True, exist_ok=True)
    Path(cfg['yamlOut']).write_text('\n'.join(yaml), encoding='utf-8', newline='\n')
    # D6: every reference outside the pack must be one we chose to reference.
    allowed = set(cfg['allowedReferences'])
    for f in files:
        for p in depot_paths(read_json(out / (flat_name(f) + '.json'))):
            if not (p.startswith(prefix + BS) or p in allowed):
                fail(f'{f} references {p}, outside the pack and not an allowed reference')
    rev12 = cfg['revision'][:12]
    lines = [f'-- Generated by build-original-stickers.ps1 (revision {rev12}). Edit the spec, not this file.',
             'LightRpVehicleStickers = {',
             f"    revision = '{rev12}',",
             f'    depotPrefix = {lua_str(prefix)},',
             f'    command = {lua_str(spec["command"])},',
             f'    maxDecalsPerCar = {cap},',
             f'    maxDecalsPerSticker = {cap},',
             '    stickers = {']
    for e in catalogue:
        models = (f"models = {{ {', '.join(lua_str(r) for r in e['models'])} }}, " if 'models' in e else '')
        lines.append(f"        {{ id = {lua_str(e['id'])}, label = {lua_str(e['label'])}, group = {lua_str(e['group'])}, "
                     f"model = {lua_str(e['model'])}, {models}decals = {e['decals']}, record = {lua_str(e['record'])}, parts = {{")
        for p in e['parts']:
            lines.append(f"            {{ record = {lua_str(p['record'])}, component = {lua_str(p['component'])}, "
                         f"decal = {lua_str(p['decal'])} }},")
        lines.append('        } },')
    lines += ['    },', '}', '']
    Path(cfg['luaOut']).parent.mkdir(parents=True, exist_ok=True)
    Path(cfg['luaOut']).write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    write_json(cfg['catalogueOut'], OrderedDict([
        ('schema', 'open77.vehicle-stickers.catalogue/1'), ('revision', rev12), ('depotPrefix', prefix),
        ('note', 'registerStickers rows (contract: id, label, group, model, decals) plus, per sticker, its holder '
                 'record and its decals: route A needs component + decal (.ent depot path), route B the decal records. '
                 'Original motifs (build-original-stickers.ps1): one sticker per theme and model.'),
        ('command', spec['command']), ('maxDecalsPerCar', cap), ('maxDecalsPerSticker', cap),
        ('stickers', catalogue), ('models', models_out),
    ]))
    write_json(cfg['packageOut'], OrderedDict([
        ('files', sorted(files)), ('decalRecords', decal_records), ('stickerRecords', sticker_records),
        ('meshes', meshes_rep), ('textures', textures),
    ]))
    print(f'ST_OCOOK_PREPARED files={len(files)} decalRecords={len(decal_records)} stickerRecords={len(sticker_records)}')


def validate(cfg):
    lv_cook.validate(cfg)       # .mesh / .ent round trip, vertex colours, texture setups and sizes
    pkg = read_json(cfg['packageOut'])
    print(f'ST_OCOOK_ROUNDTRIP_OK files={len(pkg["files"])} textures={len(pkg["texturesChecked"])}')


# --------------------------------------------------------------------------- no vanilla bytes
def name_hash(name):
    """A CR2W names-table hash: FNV-1a 64 of the name, its two halves xor-ed (measured on 2.31
    meshes: CMesh -> 0x6aecd0e1); the empty name 0."""
    if not name:
        return 0
    h = 0xCBF29CE484222325
    for x in name:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return (h & 0xFFFFFFFF) ^ (h >> 32)


def name_region(data):
    """(start, end) of a CR2W file's strings and names tables when they are vocabulary only:
    printable names, and a names table of (offset, name_hash(name)) entries, each verified.
    None when the file is not CR2W or any entry does not verify."""
    if len(data) < 160 or data[:4] != b'CR2W':
        return None
    so, size, _ = struct.unpack_from('<III', data, 40)          # table 0: the strings, bytes
    no, count, _ = struct.unpack_from('<III', data, 52)         # table 1: the names, 8 bytes each
    end = no + 8 * count
    if no != so + size or end > len(data) or any(not (x == 0 or 0x20 <= x < 0x7F) for x in data[so:no]):
        return None
    for k in range(count):
        off, h = struct.unpack_from('<II', data, no + 8 * k)
        stop = data.find(b'\0', so + off, no)
        if off >= size or stop < 0 or h != name_hash(data[so + off:stop]):
            return None
    return so, end


def cr2w_names(data):
    """The names of a CR2W file whose names table verifies (name_region), else None."""
    if name_region(data) is None:
        return None
    so, _size, _ = struct.unpack_from('<III', data, 40)
    no, count, _ = struct.unpack_from('<III', data, 52)
    return [data[so + off:data.find(b'\0', so + off, no)] for off, _ in struct.iter_unpack('<II', data[no:no + 8 * count])]


def struct_props(data, p, end, names):
    """One serialized struct at p (a 0 byte, then (name u16, type u16, size u32, value) records,
    then a 0 name): ([(name, type, value)], offset after it), or None when malformed."""
    if p >= end or data[p] != 0:
        return None
    p, out = p + 1, []
    while p + 2 <= end:
        n, = struct.unpack_from('<H', data, p)
        if n == 0:
            return out, p + 2
        if p + 8 > end:
            return None
        t, size = struct.unpack_from('<HI', data, p + 2)
        if n >= len(names) or t >= len(names) or size < 4 or p + 4 + size > end:
            return None
        out.append((names[n], names[t], data[p + 8:p + 4 + size]))
        p += 4 + size
    return None


# A vertex format descriptor (rendVertexBufferChunk.vertexLayout, a GpuWrapApiVertexLayoutDesc):
# which streams the vertices carry (PT_ packing type, PS_ usage, stream and usage index), each
# slot's stride, the slot mask and the layout hash. Two meshes with the same vertex format and
# the same leading names (the names table, above) serialize it to the same bytes: it describes
# the format and holds no vertex, index or texture data.
LAYOUT_ELEMENT_FIELDS = {
    b'type': (b'GpuWrapApiVertexPackingePackingType', b'PT_'),
    b'usage': (b'GpuWrapApiVertexPackingePackingUsage', b'PS_'),
    b'streamType': (b'GpuWrapApiVertexPackingEStreamType', b'ST_'),
    b'streamIndex': (b'Uint8', None),
    b'usageIndex': (b'Uint8', None),
}
LAYOUT_FIELDS = {b'elements': b'static:32,GpuWrapApiVertexPackingPackingElement', b'slotStrides': b'static:8,Uint8',
                 b'slotMask': b'Uint32', b'hash': b'Uint32'}


def layout_element_is_format(props, names):
    for field, ftyp, fval in props:
        want = LAYOUT_ELEMENT_FIELDS.get(field)
        if not want or want[0] != ftyp:
            return False
        if want[1] is None:
            if len(fval) != 1:
                return False
            continue
        if len(fval) != 2:
            return False
        idx, = struct.unpack('<H', fval)
        if idx >= len(names) or not names[idx].startswith(want[1]):
            return False
    return True


def layout_is_format(props, names):
    """True when a vertexLayout's properties are the vertex format and nothing else."""
    for name, typ, value in props:
        if LAYOUT_FIELDS.get(name) != typ:
            return False
        if typ == b'Uint32' and len(value) != 4:
            return False
        if name == b'slotStrides' and (len(value) != 12 or struct.unpack_from('<I', value)[0] != 8):
            return False
        if name == b'elements':
            if len(value) < 4:
                return False
            count, = struct.unpack_from('<I', value)
            if not 0 < count <= 32:
                return False
            q = 4
            for _ in range(count):
                parsed = struct_props(value, q, len(value), names)
                if not parsed or not layout_element_is_format(parsed[0], names):
                    return False
                q = parsed[1]
            if q != len(value):
                return False
    return True


def layout_regions(data):
    """(start, end) of each vertexLayout of a CR2W file that is the vertex format only
    (layout_is_format), its property header included, and the header of the chunkVertices
    struct that opens with it (name, type, size, struct prefix) when it does; [] when the names
    table does not verify."""
    names = cr2w_names(data)
    if not names or b'vertexLayout' not in names or b'GpuWrapApiVertexLayoutDesc' not in names:
        return []
    head = struct.pack('<HH', names.index(b'vertexLayout'), names.index(b'GpuWrapApiVertexLayoutDesc'))
    parent = (struct.pack('<HH', names.index(b'chunkVertices'), names.index(b'rendVertexBufferChunk'))
              if b'chunkVertices' in names and b'rendVertexBufferChunk' in names else None)
    out, start = [], 0
    while (h := data.find(head, start)) >= 0 and h + 8 <= len(data):
        start = h + 1
        end = h + 4 + struct.unpack_from('<I', data, h + 4)[0]
        if end > len(data):
            continue
        parsed = struct_props(data, h + 8, end, names)
        if parsed and parsed[1] == end and layout_is_format(parsed[0], names):
            first = h
            opens = parent and h >= 9 and data[h - 9:h - 5] == parent and data[h - 1] == 0
            if opens and h - 9 + 4 + struct.unpack_from('<I', data, h - 5)[0] >= end:
                first = h - 9
            out.append((first, end))
    return out


def scan_names(plan_path):
    """plates.cjs scan counts shared names (ASCII) and index runs as vocabulary, not the CR2W
    names table that follows the names: (offset, hash of the name) pairs, the same bytes in any
    two files that use the same leading names. Our meshes keep the container's CR2W layout, so
    they share it with every mesh of the game; for the same reason they share the serialized
    vertex format (layout_regions) with any mesh of the same format and leading names. Each
    binary block the scan reported must lie inside the strings + names tables of its vanilla
    file (every entry verified), or inside one of its vertex format descriptors (every field
    and value verified); any other shared block fails, as in plates.cjs."""
    plan = read_json(plan_path)
    scan = read_json(Path(plan['reportDir']) / 'scan.json')
    by_name = {}
    for v in plan['vanillaFiles']:
        by_name.setdefault(Path(v).name, []).append(v)
    regions, content, kinds = {}, [], {'names': 0, 'format': 0}
    window = scan['window']
    for hit in scan['binary']:
        name, off = hit.split(' = ')[0].rsplit('@', 1)
        off = int(off)
        paths = by_name.get(name) or fail(f'scan: {name} is not a file the build read')
        for p in paths:                     # same name in two folders: both must explain the block
            if p not in regions:
                data = Path(p).read_bytes()
                regions[p] = (name_region(data), layout_regions(data))
        if all(regions[p][0] and regions[p][0][0] <= off and off + window <= regions[p][0][1] for p in paths):
            kinds['names'] += 1
        elif all(any(a <= off and off + window <= b for a, b in regions[p][1]) for p in paths):
            kinds['format'] += 1
        else:
            content.append(hit)
    if content:
        fail(f'scan: {len(content)} shared 64-byte blocks of vanilla files are content, not a names table '
             f'nor a vertex format descriptor: {"; ".join(content[:8])}')
    print(f'ST_SCAN_NAMES_OK ours={len(scan["ourFiles"])} vanilla={scan["vanillaFiles"]} shared content blocks=0, '
          f'names-table blocks={kinds["names"]}, vertex-format blocks={kinds["format"]} '
          f'in {len({h.split("@")[0] for h in scan["binary"]})} files, '
          f'name blocks={scan["vocabulary"]} ({len(scan["names"])} names), index-run blocks={len(scan["counting"])}')

if __name__ == '__main__':
    commands = {'prepare': prepare, 'validate': validate, 'scan-names': scan_names}
    if len(sys.argv) != 3 or sys.argv[1] not in commands:
        fail('usage: st_ocook.py prepare|validate <cook.json>  |  st_ocook.py scan-names <scan-plan.json>')
    arg = sys.argv[2] if sys.argv[1] == 'scan-names' else read_json(sys.argv[2])
    commands[sys.argv[1]](arg)
